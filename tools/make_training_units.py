"""One-off: build ui/training_units.js (unit list + small thumbnails for the 2v2 Training page).

    py -3.14 tools/make_training_units.py <aerial package>/wwwroot/training ui/training_units.js

Input: msdata_visible.json (id, en name, cost, group normal/boss/cpu) and thumbs/ (228x104 banners)
from aerial's 2v2 Training Extension 1.1. Output: window.TRAINING_UNITS = [[id, name, cost, group, thumb]],
thumb = a 171x78 webp data URL ("" when there is none).
"""
import base64
import io
import json
import os
import sys

from PIL import Image

src, out = sys.argv[1], sys.argv[2]
# aerial's msdata has a few wrong costs; these are the game's (player cost table 0xFF832E7F sub 0, 1.13.30)
COST_FIX = {1008001: 1500, 3001001: 3000, 3003001: 3000, 3012001: 2500, 57001001: 2000}
# game costs of the units missing from the list (hidden units a Mod Manager clone mod can make playable)
EXTRA_COSTS = {"1001002": 2000, "1013001": 1500, "1014001": 2000, "1016001": 1500, "1017001": 1500, "2001002": 2500, "2009001": 2000, "2011001": 1500, "2012001": 1500, "2015001": 1500, "2017001": 1500, "4004001": 1500, "7004002": 2000, "8003001": 1500, "10006001": 1500, "12001002": 1500, "13006001": 1500, "13007001": 1500, "14001002": 1500, "14012002": 3000, "14019001": 2000, "14023001": 1500, "14024001": 2500, "15010001": 2000, "15011001": 1500, "15012001": 1500, "16001501": 1500, "17008001": 1500, "18009001": 2000, "21010001": 1500, "33002002": 2500, "33007002": 3000, "33009001": 1500, "34001002": 2500, "34008001": 2500, "43003001": 2000, "45001001": 2000, "45004001": 2000, "47001001": 1500, "48001001": 2000, "48002001": 2000, "49006002": 2000, "50001001": 2500, "50002001": 2500, "53001001": 1500, "57002002": 2500, "59001002": 3000, "59002002": 2000, "59003002": 2500, "59004002": 1500, "62003001": 1500, "68004001": 3000, "68005001": 1500, "101002001": 1500, "999001001": 1500, "999002001": 2000, "999003001": 2000, "999004001": 2000, "999005001": 2500, "999006001": 1000, "999007001": 1000, "999008001": 1500, "999009001": 1500, "999021001": 1000, "999022001": 2000, "999024001": 1000, "999025001": 2000, "999026001": 3000, "999037001": 1500, "999051001": 1500, "999053001": 2500, "999054001": 2500, "999055001": 1500, "999056001": 1500, "999057001": 1500, "999058001": 3000, "999059001": 3000, "999060001": 1500, "999061001": 2500, "999062001": 3000, "999500001": 1500, "999600001": 1500, "999701001": 1500, "999702001": 1500, "999703001": 1500, "999704001": 1500}
units = json.load(open(os.path.join(src, "msdata_visible.json"), encoding="utf-8"))
thumbs = os.path.join(src, "thumbs")


def thumb(uid, group):
    names = [f"{uid}.png", f"{uid}.jpg"]
    if group == "boss":
        names.insert(0, f"boss_{uid}.png")
    for n in names:
        p = os.path.join(thumbs, n)
        if os.path.exists(p):
            im = Image.open(p).convert("RGB").resize((171, 78), Image.LANCZOS)
            b = io.BytesIO()
            im.save(b, "WEBP", quality=72, method=6)
            return "data:image/webp;base64," + base64.b64encode(b.getvalue()).decode()
    return ""


rows = []
for u in units:
    g = u.get("group") or "normal"
    rows.append([u["id"], u["en"].strip(), COST_FIX.get(u["id"], u["cost"]), g, thumb(u["id"], g)])
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("// generated by tools/make_training_units.py: [id, name, cost, group, thumbnail]\n")
    f.write("window.TRAINING_UNITS = [\n")
    for r in rows:
        f.write(json.dumps(r, ensure_ascii=False) + ",\n")
    f.write("];\n")
    f.write("// costs of the units that are not in the list (hidden units a Mod Manager clone mod can make playable)\n")
    f.write("window.TRAINING_EXTRA_COSTS = " + json.dumps(EXTRA_COSTS, separators=(",", ":")) + ";\n")
print(len(rows), "units,", os.path.getsize(out), "bytes")
